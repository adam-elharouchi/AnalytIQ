"""
Container-isolated execution backend for the code sandbox.

This is the kernel-enforced counterpart to the in-process defences in
``services.code_runner``. When ``config.SANDBOX_USE_CONTAINER`` is on, code_runner
runs each student invocation through :func:`run_in_container` instead of a host
subprocess. The *same* harness (generated by code_runner) and the student source
are written to a throwaway tempdir and bind-mounted READ-ONLY into an ephemeral,
locked-down container:

    docker run --rm -i
        --network <none|egress-filtered>   # no access to internal net / metadata
        --read-only                         # immutable rootfs
        --tmpfs /tmp:rw,noexec,nosuid,nodev # only scratch is writable
        --memory 512m --memory-swap 512m    # cgroup RAM cap, no swap
        --cpus 1.0                          # cgroup CPU cap
        --pids-limit 64                     # fork-bomb ceiling
        --cap-drop ALL                      # no Linux capabilities
        --security-opt no-new-privileges    # no setuid escalation
        --user 10001:10001                  # non-root
        [--runtime runsc]                   # optional gVisor kernel isolation
        -v <tmpdir>:/opt/run:ro <image> python /opt/run/<harness>.py <args…>

Because the harness stays in code_runner.py, grading behaviour is byte-identical
to the host runner — only the *execution boundary* changes.

The module imports cleanly with no Docker present (``shutil.which`` is called
lazily). If the CLI is missing at run time, :class:`ContainerUnavailable` is
raised so the caller can FAIL CLOSED rather than silently run on the host.
"""

# str | None annotations below need PEP 604 lazy evaluation on Python 3.9.
from __future__ import annotations

import logging
import os
import secrets
import shutil
import subprocess
from typing import Mapping, Sequence

import config

logger = logging.getLogger(__name__)

# Read-only mount point for the harness + student code inside the container.
# code_runner references this when building the argv (e.g. MOUNT + "/code.py").
MOUNT = "/opt/run"


class ContainerUnavailable(RuntimeError):
    """Raised when the container CLI/daemon is not usable, so callers fail closed."""


def _cli_path() -> str | None:
    """Absolute path to the configured container CLI, or None if not found."""
    return shutil.which(config.SANDBOX_CONTAINER_CLI)


def available() -> bool:
    """True when the configured container CLI is on PATH."""
    return _cli_path() is not None


def build_argv(
    host_dir: str, entry: str, args: Sequence[str], network: str, name: str
) -> list[str]:
    """
    Construct the fully-hardened ``docker run`` argv. Pure function (no side
    effects) so it can be unit-tested without a daemon.

    host_dir : tempdir holding the harness + student code (bind-mounted :ro)
    entry    : harness filename inside host_dir (run as python /opt/run/<entry>)
    args     : extra argv passed to the harness (file refs use the MOUNT path)
    network  : value for --network ("none" or an egress-filtered network name)
    name     : container name, used for reliable kill-on-timeout cleanup
    """
    cli = config.SANDBOX_CONTAINER_CLI
    argv: list[str] = [
        cli,
        "run",
        "--rm",
        "-i",
        "--name",
        name,
        "--network",
        network,
        "--read-only",
        "--tmpfs",
        # nosec B108 - this "/tmp" is a path INSIDE the container, not on the
        # host: it declares a tmpfs mount that is itself a hardening measure
        # (noexec, nosuid, nodev, size-capped). No host temp file is involved.
        f"/tmp:rw,noexec,nosuid,nodev,size={config.SANDBOX_CONTAINER_TMPFS_SIZE}",  # nosec B108
        "--memory",
        config.SANDBOX_CONTAINER_MEMORY,
        # Equal memory-swap => zero swap; the cap is real RAM, not RAM+swap.
        "--memory-swap",
        config.SANDBOX_CONTAINER_MEMORY,
        "--cpus",
        str(config.SANDBOX_CONTAINER_CPUS),
        "--pids-limit",
        str(config.SANDBOX_CONTAINER_PIDS),
        "--cap-drop",
        "ALL",
        "--security-opt",
        "no-new-privileges",
        "--user",
        "10001:10001",
        "-v",
        f"{host_dir}:{MOUNT}:ro",
        "-w",
        # nosec B108 - container-internal working directory (the tmpfs mounted
        # above), not a host path.
        "/tmp",  # nosec B108
        # Neutral, secret-free env (mirrors code_runner's _SANDBOX_ENV intent).
        # --network none already blocks exfil; this keeps interpreter config sane.
        "-e",
        "HOME=/tmp",
        "-e",
        "TMPDIR=/tmp",
        "-e",
        "PYTHONDONTWRITEBYTECODE=1",
        "-e",
        "PYTHONUNBUFFERED=1",
    ]
    if config.SANDBOX_CONTAINER_RUNTIME:
        argv += ["--runtime", config.SANDBOX_CONTAINER_RUNTIME]
    argv += [config.SANDBOX_CONTAINER_IMAGE, "python", f"{MOUNT}/{entry}", *args]
    return argv


def _write_inputs(host_dir: str, files: Mapping[str, str]) -> None:
    """Write harness+code into host_dir with perms the in-container uid can read.

    TemporaryDirectory is 0o700 owned by the host app uid, which the container's
    uid 10001 cannot traverse. Relax to world-readable (the dir is a throwaway
    holding only the student's own code + the public harness — no secrets).
    """
    # nosec B103 - 0o755 is required, not accidental: the container runs as uid
    # 10001 and cannot traverse the 0o700 TemporaryDirectory owned by the host
    # app uid. The directory is a per-run throwaway containing only the student's
    # own submission and the public test harness, so world-readable costs nothing.
    os.chmod(host_dir, 0o755)  # nosec B103
    for name, content in files.items():
        # Reject path traversal in filenames; callers pass fixed basenames.
        if os.path.sep in name or name in (".", ".."):
            raise ValueError(f"invalid sandbox input filename: {name!r}")
        path = os.path.join(host_dir, name)
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(content)
        os.chmod(path, 0o644)


def run_in_container(
    *,
    files: Mapping[str, str],
    entry: str,
    args: Sequence[str],
    timeout: int,
    network: str,
) -> subprocess.CompletedProcess:
    """
    Execute ``python /opt/run/<entry> <args…>`` in a locked-down container.

    Returns a CompletedProcess whose ``.stdout`` / ``.stderr`` the caller parses
    exactly as it parses the host subprocess (code_runner._parse_proc).

    Raises
    ------
    ContainerUnavailable        if the container CLI is not on PATH.
    subprocess.TimeoutExpired   if the run exceeds timeout (container is killed
                                first so it cannot outlive the request).
    """
    if _cli_path() is None:
        raise ContainerUnavailable(
            f"container CLI {config.SANDBOX_CONTAINER_CLI!r} not found on PATH; "
            "SANDBOX_USE_CONTAINER is on but no runtime is available"
        )

    name = f"aq-sbx-{secrets.token_hex(8)}"
    # TemporaryDirectory cleanup runs even if docker leaves the :ro mount busy,
    # because the container is always gone (--rm / kill) before we exit the block.
    import tempfile

    with tempfile.TemporaryDirectory(prefix="aq_ctr_") as host_dir:
        _write_inputs(host_dir, files)
        argv = build_argv(host_dir, entry, list(args), network, name)
        # +grace for image/container spin-up before the host kill-switch fires.
        wall_timeout = timeout + config.SANDBOX_CONTAINER_STARTUP_GRACE
        try:
            return subprocess.run(
                argv,
                capture_output=True,
                text=True,
                timeout=wall_timeout,
                stdin=subprocess.DEVNULL,
            )
        except subprocess.TimeoutExpired:
            # Killing the `docker run` client does NOT stop the container — it is
            # daemon-managed. Kill it by name so untrusted code cannot outlive the
            # request. Best-effort; --rm reaps the killed container. Use the same
            # CLI identifier build_argv uses so PATH resolution is consistent.
            _force_kill(config.SANDBOX_CONTAINER_CLI, name)
            raise


def _force_kill(cli: str, name: str) -> None:
    try:
        subprocess.run(
            [cli, "kill", name],
            capture_output=True,
            text=True,
            timeout=10,
            stdin=subprocess.DEVNULL,
        )
    except Exception as exc:  # noqa: BLE001 - cleanup must never raise
        logger.warning("Failed to kill timed-out sandbox container %s: %s", name, exc)
