-- ============================================================================
-- Migration 000 — Initial schema (baseline)
--
-- Creates the complete AnalytIQ schema from nothing, so that
--
--     createdb analytiq && python db_migrate.py
--
-- produces a working database with no manual steps. Before this file existed
-- the only full DDL for the content tables lived in tests/integration/conftest.py
-- and scripts/create_tables.py, and migrations 001-013 could only *patch* a
-- schema somebody had already created by hand.
--
-- HOW THIS COEXISTS WITH 001-013
--
--   * This file is a snapshot of the schema as it stands after 001-013 have been
--     applied — not a replacement for them. It is numbered 000 so db_migrate.py
--     (which sorts migrations by filename) runs it first on a fresh database;
--     001-013 then apply on top and find everything already in place.
--
--   * Every statement is CREATE ... IF NOT EXISTS or ADD COLUMN IF NOT EXISTS,
--     so on a database that already ran 001-013 this file is a no-op: it is
--     recorded in schema_migrations and changes nothing. There are no ALTER
--     COLUMN / DROP / RENAME / data statements anywhere in it, by design.
--
--   * Do not edit this file to add new columns or tables. It is frozen history.
--     Schema changes go in a new numbered migration, which both fresh and
--     existing databases then apply in the normal way.
--
-- CONVENTIONS
--
--   * user_id, tenant_id, class_id, chapter_id and exercise_id are VARCHAR
--     strings (UUID text or human-readable codes), never integers.
--   * Tables whose surrogate key is `id SERIAL` also carry a UNIQUE business
--     key — the application joins on the business key, not on id.
--   * gen_random_uuid() is a core function from PostgreSQL 13 onwards; this
--     schema therefore requires PostgreSQL >= 13.
-- ============================================================================


-- ---------------------------------------------------------------------------
-- 1. Tenants (multi-tenancy root; must precede users for the tenant_id FK)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS tenants (
    tenant_id    VARCHAR(255) PRIMARY KEY DEFAULT gen_random_uuid()::text,
    name         VARCHAR(255) NOT NULL,
    lti_issuer   VARCHAR(500) UNIQUE,            -- maps 1:1 with lti_configurations.issuer
    is_active    BOOLEAN      DEFAULT true,
    created_at   TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
    updated_at   TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
    email_domain VARCHAR(255)                    -- NULL = no auto-assignment at signup
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_tenants_email_domain
    ON tenants (email_domain)
    WHERE email_domain IS NOT NULL;


-- ---------------------------------------------------------------------------
-- 2. Users
--
-- password_hash is NULL for LTI-only and SSO-only accounts.
-- sso_provider_id / sso_subject are added further down, once
-- tenant_sso_providers exists (users <-> tenant_sso_providers is a FK cycle).
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS users (
    id                      SERIAL       PRIMARY KEY,
    user_id                 VARCHAR(255) UNIQUE NOT NULL,
    name                    VARCHAR(255) NOT NULL,
    email                   VARCHAR(255) UNIQUE NOT NULL,
    password_hash           VARCHAR(255),
    role                    VARCHAR(50),         -- student | professor | tenant_admin | superadmin
    lti_sub                 VARCHAR(255),
    lti_issuer              VARCHAR(500),
    created_at              TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
    updated_at              TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
    tenant_id               VARCHAR(255) REFERENCES tenants(tenant_id) ON DELETE SET NULL,
    is_super_admin          BOOLEAN      DEFAULT false,
    account_status          VARCHAR(50)  DEFAULT 'active',
    requires_password_reset BOOLEAN      DEFAULT false,
    last_login              TIMESTAMP,
    UNIQUE (lti_sub, lti_issuer)
    -- sso_provider_id, sso_subject, archived_at and token_version are added in
    -- section 3, in the order a database migrated through 004/012/013 has them
);

CREATE INDEX IF NOT EXISTS idx_users_email   ON users (email);
CREATE INDEX IF NOT EXISTS idx_users_user_id ON users (user_id);


-- ---------------------------------------------------------------------------
-- 3. Per-tenant SSO providers, then the SSO identity columns on users
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS tenant_sso_providers (
    provider_id            VARCHAR(255) PRIMARY KEY DEFAULT gen_random_uuid()::text,
    tenant_id              VARCHAR(255) NOT NULL REFERENCES tenants(tenant_id) ON DELETE CASCADE,
    provider_name          VARCHAR(100) NOT NULL,
    provider_type          VARCHAR(20)  NOT NULL,  -- google | microsoft | oidc
    client_id              TEXT         NOT NULL,
    client_secret          TEXT         NOT NULL,  -- Fernet-encrypted with SECRET_KEY
    discovery_url          TEXT         NOT NULL,  -- OIDC .well-known endpoint
    allowed_domains        TEXT[],
    role_mapping_attribute VARCHAR(100),
    role_mapping           JSONB        DEFAULT '{}',
    default_role           VARCHAR(50)  DEFAULT 'student',
    is_enabled             BOOLEAN      DEFAULT true,
    created_by             VARCHAR(255) REFERENCES users(user_id) ON DELETE SET NULL,
    created_at             TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
    updated_at             TIMESTAMP    DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_sso_providers_tenant
    ON tenant_sso_providers (tenant_id);
CREATE INDEX IF NOT EXISTS idx_sso_providers_enabled
    ON tenant_sso_providers (is_enabled)
    WHERE is_enabled = true;

ALTER TABLE users
    ADD COLUMN IF NOT EXISTS sso_provider_id VARCHAR(255)
        REFERENCES tenant_sso_providers(provider_id) ON DELETE SET NULL,
    ADD COLUMN IF NOT EXISTS sso_subject TEXT;

CREATE UNIQUE INDEX IF NOT EXISTS uq_sso_user_identity
    ON users (sso_provider_id, sso_subject)
    WHERE sso_provider_id IS NOT NULL;

-- The last two users columns, kept here so a freshly built database has the
-- same column order as one that migrated through 012 and 013.
ALTER TABLE users
    ADD COLUMN IF NOT EXISTS archived_at   TIMESTAMP,          -- soft delete (tenant removed)
    ADD COLUMN IF NOT EXISTS token_version INTEGER NOT NULL DEFAULT 0;  -- JWT revocation counter

CREATE INDEX IF NOT EXISTS idx_users_archived_at ON users (archived_at)
    WHERE archived_at IS NOT NULL;


-- ---------------------------------------------------------------------------
-- 4. Per-user satellite tables
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS user_profiles (
    id              SERIAL       PRIMARY KEY,
    user_id         VARCHAR(255) UNIQUE NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    full_name       VARCHAR(255),
    bio             TEXT,
    profile_picture TEXT,
    created_at      TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP    DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS user_settings (
    id                  SERIAL       PRIMARY KEY,
    user_id             VARCHAR(255) UNIQUE NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    email_notifications BOOLEAN      DEFAULT false,
    dark_mode           BOOLEAN      DEFAULT false,
    created_at          TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMP    DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS user_preferences (
    id               SERIAL       PRIMARY KEY,
    user_id          VARCHAR(255) UNIQUE NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    current_language VARCHAR(50)  DEFAULT 'python',
    gemini_model     VARCHAR(100) DEFAULT 'gemini-3.5-flash',
    ai_provider      VARCHAR(50)  DEFAULT 'gemini',
    created_at       TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
    updated_at       TIMESTAMP    DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS ai_agent_digest (
    id             SERIAL       PRIMARY KEY,
    user_id        VARCHAR(255) UNIQUE NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    goal           TEXT,
    constraints    TEXT,
    decisions      TEXT,
    current_state  TEXT,
    open_questions TEXT,
    created_at     TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
    updated_at     TIMESTAMP    DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS ai_agent_memory (
    id          SERIAL       PRIMARY KEY,
    user_id     VARCHAR(255) NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    memory_item TEXT         NOT NULL,
    created_at  TIMESTAMP    DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_ai_memory_user_id ON ai_agent_memory (user_id);


-- ---------------------------------------------------------------------------
-- 5. AI chat history
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS conversations (
    id              SERIAL       PRIMARY KEY,
    conversation_id VARCHAR(255) UNIQUE NOT NULL,
    user_id         VARCHAR(255) NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    title           VARCHAR(500),
    archived        BOOLEAN      DEFAULT false,
    deleted         BOOLEAN      DEFAULT false,   -- soft delete
    created_at      TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP    DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_conversations_user_id
    ON conversations (user_id);
CREATE INDEX IF NOT EXISTS idx_conversations_conversation_id
    ON conversations (conversation_id);

CREATE TABLE IF NOT EXISTS conversation_messages (
    id              SERIAL       PRIMARY KEY,
    conversation_id VARCHAR(255) NOT NULL
                        REFERENCES conversations(conversation_id) ON DELETE CASCADE,
    role            VARCHAR(50)  NOT NULL,
    content         TEXT         NOT NULL,
    message_order   INTEGER      NOT NULL,
    created_at      TIMESTAMP    DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_messages_conversation_id
    ON conversation_messages (conversation_id);


-- ---------------------------------------------------------------------------
-- 6. Course content
--
-- class_id doubles as the student join code.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS classes (
    class_id          VARCHAR(255) PRIMARY KEY,
    professor_id      VARCHAR(255) NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    name              VARCHAR(255) NOT NULL,
    description       TEXT,
    lti_context_id    VARCHAR(500),
    lti_issuer        VARCHAR(500),
    nrps_context_url  TEXT,                       -- LTI Names & Roles endpoint
    ags_enabled       BOOLEAN      DEFAULT false, -- LTI Assignment & Grade Services
    ags_lineitems_url TEXT,
    created_at        TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
    updated_at        TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
    tenant_id         VARCHAR(255) REFERENCES tenants(tenant_id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS class_enrollments (
    id          SERIAL       PRIMARY KEY,
    class_id    VARCHAR(255) NOT NULL REFERENCES classes(class_id) ON DELETE CASCADE,
    student_id  VARCHAR(255) NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    enrolled_at TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (class_id, student_id)
);

CREATE TABLE IF NOT EXISTS class_chapters (
    chapter_id     VARCHAR(255) PRIMARY KEY,
    class_id       VARCHAR(255) NOT NULL REFERENCES classes(class_id) ON DELETE CASCADE,
    title          VARCHAR(255) NOT NULL,
    description    TEXT,
    chapter_number INTEGER,
    pdf_url        TEXT,                          -- Supabase Storage URL
    pdf_filename   VARCHAR(255),
    pdf_data       BYTEA,                         -- inline bytes (Supabase-less fallback)
    created_at     TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
    updated_at     TIMESTAMP    DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS class_exercises (
    exercise_id     VARCHAR(255) PRIMARY KEY,
    chapter_id      VARCHAR(255) NOT NULL
                        REFERENCES class_chapters(chapter_id) ON DELETE CASCADE,
    class_id        VARCHAR(255) NOT NULL REFERENCES classes(class_id) ON DELETE CASCADE,
    title           VARCHAR(500) NOT NULL,
    description     TEXT,
    difficulty      VARCHAR(50),
    solution_code   TEXT,                         -- professor-visible reference solution
    exercise_number INTEGER,
    created_by      VARCHAR(255),
    function_name   VARCHAR(255) DEFAULT 'solution',
    language        VARCHAR(50)  DEFAULT 'Python',
    test_cases      JSONB,                        -- [{description, input, expected_output, weight}]
    created_at      TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP    DEFAULT CURRENT_TIMESTAMP
    -- generation_event_id is added in section 10, once the flywheel table exists
);

CREATE INDEX IF NOT EXISTS idx_class_exercises_has_test_cases
    ON class_exercises ((test_cases IS NOT NULL));

-- class_resources deliberately carries no foreign keys: it predates the FK
-- conventions used elsewhere and holds rows for classes created by hand.
CREATE TABLE IF NOT EXISTS class_resources (
    resource_id   VARCHAR(255) PRIMARY KEY,
    class_id      VARCHAR(255) NOT NULL,
    user_id       VARCHAR(255) NOT NULL,          -- uploader
    title         VARCHAR(255) NOT NULL,
    description   TEXT,
    resource_type VARCHAR(50)  NOT NULL,          -- pdf | link | dataset | ...
    resource_url  TEXT,
    file_data     BYTEA,
    filename      VARCHAR(255),
    created_at    TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMP    DEFAULT CURRENT_TIMESTAMP
);


-- ---------------------------------------------------------------------------
-- 7. Student progress
--
-- practice_progress holds the current best per (user, exercise); exercise_id is
-- not a foreign key because it also stores ids of built-in practice exercises
-- that do not live in class_exercises. class_exercise_id is the class-assignment
-- link used by the class progress and leaderboard queries.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS practice_progress (
    id                    SERIAL        PRIMARY KEY,
    user_id               VARCHAR(255)  NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    exercise_id           VARCHAR(255)  NOT NULL,
    exercise_title        VARCHAR(500),
    class_id              VARCHAR(255),
    class_exercise_id     VARCHAR(255),
    best_score            INTEGER       DEFAULT 0,
    best_accuracy         DECIMAL(5,2)  DEFAULT 0,
    best_time             INTEGER,
    total_attempts        INTEGER       DEFAULT 0,
    last_attempt_score    INTEGER,
    last_attempt_accuracy DECIMAL(5,2),
    last_attempt_time     INTEGER,
    completed             BOOLEAN       DEFAULT false,
    last_completed_at     TIMESTAMP,
    created_at            TIMESTAMP     DEFAULT CURRENT_TIMESTAMP,
    updated_at            TIMESTAMP     DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (user_id, exercise_id)                 -- the upsert's ON CONFLICT target
);

CREATE INDEX IF NOT EXISTS idx_practice_user_id ON practice_progress (user_id);

CREATE TABLE IF NOT EXISTS exercise_attempts (
    id             SERIAL       PRIMARY KEY,
    user_id        VARCHAR(255) NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    exercise_id    VARCHAR(255) NOT NULL,
    score          INTEGER      NOT NULL,
    accuracy       DECIMAL(5,2) NOT NULL,
    time_spent     INTEGER      NOT NULL,
    attempt_number INTEGER      NOT NULL,
    created_at     TIMESTAMP    DEFAULT CURRENT_TIMESTAMP
);


-- ---------------------------------------------------------------------------
-- 8. Auth and audit
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS password_resets (
    id         SERIAL       PRIMARY KEY,
    email      VARCHAR(255) NOT NULL,
    token      VARCHAR(255) NOT NULL,
    expires_at TIMESTAMP    NOT NULL,
    created_at TIMESTAMP    DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_password_resets_token ON password_resets (token);
CREATE INDEX IF NOT EXISTS idx_password_resets_email ON password_resets (email);

-- FERPA mutation log. user_id is TEXT and unconstrained so an audit row
-- survives deletion of the actor it refers to.
CREATE TABLE IF NOT EXISTS audit_log (
    id            BIGSERIAL   PRIMARY KEY,
    user_id       TEXT,
    action        TEXT        NOT NULL,
    resource_type TEXT,
    resource_id   TEXT,
    ip_address    TEXT,
    details       JSONB,
    created_at    TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_audit_log_user_id    ON audit_log (user_id);
CREATE INDEX IF NOT EXISTS idx_audit_log_created_at ON audit_log (created_at DESC);


-- ---------------------------------------------------------------------------
-- 9. Platform administration
--
-- platform_config is the pre-003 shape (key/value only). Migration 003 ships a
-- wider CREATE TABLE with updated_by/updated_at, but every deployed database
-- already had this table when 003 ran, so 003's CREATE was a no-op there and
-- this is the shape that actually exists. Only key and value are read by the
-- application. 003 still seeds its default rows on top.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS platform_config (
    key   VARCHAR(255) PRIMARY KEY,
    value TEXT         NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS announcements (
    announcement_id VARCHAR(255) PRIMARY KEY DEFAULT gen_random_uuid()::text,
    title           VARCHAR(255) NOT NULL,
    message         TEXT         NOT NULL,
    type            VARCHAR(20)  NOT NULL DEFAULT 'info',  -- info | warning | danger | success
    target_roles    TEXT[]       DEFAULT '{}',             -- empty = all roles
    is_active       BOOLEAN      DEFAULT true,
    expires_at      TIMESTAMP,
    created_by      VARCHAR(255) REFERENCES users(user_id) ON DELETE SET NULL,
    created_at      TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
    tenant_id       VARCHAR(255) REFERENCES tenants(tenant_id) ON DELETE SET NULL
                                                             -- NULL = platform-wide
);

CREATE INDEX IF NOT EXISTS idx_announcements_tenant_id ON announcements (tenant_id);

CREATE TABLE IF NOT EXISTS ip_blocklist (
    id         SERIAL       PRIMARY KEY,
    ip_address VARCHAR(100) NOT NULL UNIQUE,
    reason     TEXT,
    blocked_by VARCHAR(255) REFERENCES users(user_id) ON DELETE SET NULL,
    created_at TIMESTAMP    DEFAULT CURRENT_TIMESTAMP
);


-- ---------------------------------------------------------------------------
-- 10. LTI 1.3
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS lti_configurations (
    config_id      VARCHAR(255) PRIMARY KEY DEFAULT gen_random_uuid()::text,
    platform_name  VARCHAR(255) NOT NULL,
    issuer         VARCHAR(500) NOT NULL,
    client_id      VARCHAR(255) NOT NULL,
    auth_login_url TEXT         NOT NULL,
    auth_token_url TEXT         NOT NULL,
    key_set_url    TEXT         NOT NULL,
    deployment_ids TEXT[]       DEFAULT '{}',
    created_by     VARCHAR(255) REFERENCES users(user_id) ON DELETE SET NULL,
    created_at     TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
    updated_at     TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
    tenant_id      VARCHAR(255) REFERENCES tenants(tenant_id) ON DELETE CASCADE,
    UNIQUE (issuer, client_id)
);

CREATE TABLE IF NOT EXISTS lti_sessions (
    session_id       VARCHAR(255) PRIMARY KEY,   -- the OIDC state parameter
    user_id          VARCHAR(255) REFERENCES users(user_id) ON DELETE CASCADE,
    class_id         VARCHAR(255) REFERENCES classes(class_id) ON DELETE SET NULL,
    nrps_context_url TEXT,
    lti_context_id   TEXT,
    issuer           VARCHAR(500),
    client_id        VARCHAR(255),
    launch_data      JSONB,                      -- decoded launch claims
    expires_at       TIMESTAMP    NOT NULL,
    created_at       TIMESTAMP    DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_lti_sessions_user_id  ON lti_sessions (user_id);
CREATE INDEX IF NOT EXISTS idx_lti_sessions_class_id ON lti_sessions (class_id);
CREATE INDEX IF NOT EXISTS idx_lti_sessions_expires  ON lti_sessions (expires_at);


-- ---------------------------------------------------------------------------
-- 11. Data flywheel
--
-- exercise_id and user_id are deliberately unconstrained here: these tables
-- record events about exercises that may since have been deleted, and about
-- built-in practice exercises that never had a class_exercises row.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS exercise_generation_events (
    id                      UUID         PRIMARY KEY DEFAULT gen_random_uuid(),
    exercise_id             VARCHAR(255),
    class_id                VARCHAR(255) REFERENCES classes(class_id) ON DELETE SET NULL,
    chapter_id              VARCHAR(255) REFERENCES class_chapters(chapter_id) ON DELETE SET NULL,
    tenant_id               TEXT,

    -- what went in
    source_content_hash     VARCHAR(64),
    source_content_type     VARCHAR(50),
    source_char_count       INTEGER,
    was_truncated           BOOLEAN      DEFAULT false,
    detected_language       VARCHAR(20),
    detected_topics         JSONB        DEFAULT '[]'::jsonb,

    -- what we asked the model
    gemini_model            VARCHAR(100),
    prompt_template_version VARCHAR(50),
    prompt_tokens           INTEGER,
    completion_tokens       INTEGER,
    generation_params       JSONB        DEFAULT '{}'::jsonb,

    -- what came out
    difficulty_requested    VARCHAR(20),
    difficulty_generated    VARCHAR(20),
    exercise_type           VARCHAR(50),
    exercise_structure      JSONB        DEFAULT '{}'::jsonb,
    num_test_cases          INTEGER,
    generation_time_ms      INTEGER,

    created_at              TIMESTAMPTZ  DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_gen_events_exercise ON exercise_generation_events (exercise_id);
CREATE INDEX IF NOT EXISTS idx_gen_events_class    ON exercise_generation_events (class_id);
CREATE INDEX IF NOT EXISTS idx_gen_events_chapter  ON exercise_generation_events (chapter_id);
CREATE INDEX IF NOT EXISTS idx_gen_events_created  ON exercise_generation_events (created_at);

-- Back-link from an exercise to the generation run that produced it.
ALTER TABLE class_exercises
    ADD COLUMN IF NOT EXISTS generation_event_id UUID
        REFERENCES exercise_generation_events(id) ON DELETE SET NULL;

CREATE TABLE IF NOT EXISTS exercise_outcome_events (
    id                  UUID         PRIMARY KEY DEFAULT gen_random_uuid(),
    exercise_id         VARCHAR(255),
    generation_event_id UUID         REFERENCES exercise_generation_events(id) ON DELETE SET NULL,
    user_id             TEXT,
    class_id            VARCHAR(255),
    tenant_id           TEXT,

    -- submission context
    attempt_number      INTEGER,
    time_spent_seconds  INTEGER,
    hints_requested     INTEGER      DEFAULT 0,
    ai_chat_messages    INTEGER      DEFAULT 0,
    code_char_count     INTEGER,

    -- grading results
    passed              BOOLEAN,
    total_score         NUMERIC(5,2),
    correctness_score   NUMERIC(5,2),
    quality_score       NUMERIC(5,2),
    tests_total         INTEGER,
    tests_passed        INTEGER,
    test_results        JSONB        DEFAULT '[]'::jsonb,
    error_category      VARCHAR(50),
    execution_time_ms   INTEGER,

    created_at          TIMESTAMPTZ  DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_outcome_exercise  ON exercise_outcome_events (exercise_id);
CREATE INDEX IF NOT EXISTS idx_outcome_user      ON exercise_outcome_events (user_id);
CREATE INDEX IF NOT EXISTS idx_outcome_gen_event ON exercise_outcome_events (generation_event_id);
CREATE INDEX IF NOT EXISTS idx_outcome_created   ON exercise_outcome_events (created_at);

-- Per-exercise rollup, recomputed by a Celery task.
CREATE TABLE IF NOT EXISTS exercise_quality_scores (
    id                          UUID         PRIMARY KEY DEFAULT gen_random_uuid(),
    exercise_id                 VARCHAR(255) UNIQUE NOT NULL,
    generation_event_id         UUID         REFERENCES exercise_generation_events(id) ON DELETE SET NULL,

    total_attempts              INTEGER      DEFAULT 0,
    unique_students             INTEGER      DEFAULT 0,
    first_attempt_pass_rate     FLOAT,
    overall_pass_rate           FLOAT,
    avg_attempts_to_pass        FLOAT,
    median_time_to_pass_seconds INTEGER,
    avg_hints_before_pass       FLOAT,
    dropout_rate                FLOAT,

    quality_score               FLOAT,
    quality_label               VARCHAR(20),
    dominant_error_category     VARCHAR(50),
    common_failure_pattern      JSONB        DEFAULT '{}'::jsonb,

    last_computed_at            TIMESTAMPTZ  DEFAULT NOW(),
    sample_size                 INTEGER
);


-- ---------------------------------------------------------------------------
-- 12. Student portfolios (public at /portfolio/{slug})
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS portfolio_profiles (
    id                    VARCHAR(255) PRIMARY KEY DEFAULT gen_random_uuid()::text,
    user_id               VARCHAR(255) NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    slug                  VARCHAR(60)  NOT NULL UNIQUE,

    -- branding
    portfolio_title       VARCHAR(100),
    display_name          VARCHAR(100),
    headline              VARCHAR(200),
    bio                   TEXT,
    avatar_url            VARCHAR(500),

    -- theme
    accent_color          VARCHAR(7)   DEFAULT '#2569f4',
    layout_style          VARCHAR(20)  DEFAULT 'grid',

    -- links
    linkedin_url          VARCHAR(300),
    github_username       VARCHAR(80),
    personal_website      VARCHAR(300),

    is_public             BOOLEAN      DEFAULT false,

    -- GitHub sync
    github_access_token   TEXT,
    github_repo_name      VARCHAR(200) DEFAULT 'analytiq-portfolio',
    github_sync_enabled   BOOLEAN      DEFAULT false,
    github_last_synced_at TIMESTAMPTZ,

    created_at            TIMESTAMPTZ  DEFAULT NOW(),
    updated_at            TIMESTAMPTZ  DEFAULT NOW(),

    CONSTRAINT uq_portfolio_user UNIQUE (user_id)
);

CREATE INDEX IF NOT EXISTS idx_portfolio_slug ON portfolio_profiles (slug);
CREATE INDEX IF NOT EXISTS idx_portfolio_user ON portfolio_profiles (user_id);

CREATE TABLE IF NOT EXISTS portfolio_items (
    id                  VARCHAR(255) PRIMARY KEY DEFAULT gen_random_uuid()::text,
    portfolio_id        VARCHAR(255) NOT NULL
                            REFERENCES portfolio_profiles(id) ON DELETE CASCADE,

    item_type           VARCHAR(20)  NOT NULL CHECK (item_type IN (
                            'class_exercise',
                            'personal_project',
                            'external_link'
                        )),

    -- set for item_type = 'class_exercise'
    exercise_id         VARCHAR(255) REFERENCES class_exercises(exercise_id) ON DELETE SET NULL,
    class_id            VARCHAR(255) REFERENCES classes(class_id) ON DELETE SET NULL,

    title               VARCHAR(200) NOT NULL,
    description         TEXT,
    language            VARCHAR(30),
    code_content        TEXT,

    -- last in-portfolio execution
    last_output         TEXT,
    last_error          TEXT,
    last_run_at         TIMESTAMPTZ,
    project_status      VARCHAR(20)  DEFAULT 'draft'
                            CHECK (project_status IN ('draft', 'published')),

    external_url        VARCHAR(500),
    tags                JSONB        DEFAULT '[]'::jsonb,

    -- denormalised provenance, shown on the public page
    source_class_name   VARCHAR(200),
    source_chapter_name VARCHAR(200),
    source_institution  VARCHAR(200),
    score               DECIMAL(5,2),
    show_score          BOOLEAN      DEFAULT false,

    display_order       INTEGER      DEFAULT 0,
    is_visible          BOOLEAN      DEFAULT true,
    is_pinned           BOOLEAN      DEFAULT false,

    github_synced       BOOLEAN      DEFAULT false,
    github_file_path    VARCHAR(300),
    github_commit_sha   VARCHAR(40),

    last_saved_at       TIMESTAMPTZ,
    completed_at        TIMESTAMPTZ,
    created_at          TIMESTAMPTZ  DEFAULT NOW(),
    updated_at          TIMESTAMPTZ  DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_pitems_portfolio ON portfolio_items (portfolio_id);
CREATE INDEX IF NOT EXISTS idx_pitems_type      ON portfolio_items (item_type);
CREATE INDEX IF NOT EXISTS idx_pitems_order     ON portfolio_items (portfolio_id, display_order);
CREATE INDEX IF NOT EXISTS idx_pitems_status    ON portfolio_items (project_status);

CREATE TABLE IF NOT EXISTS portfolio_views (
    id           VARCHAR(255) PRIMARY KEY DEFAULT gen_random_uuid()::text,
    portfolio_id VARCHAR(255) NOT NULL
                     REFERENCES portfolio_profiles(id) ON DELETE CASCADE,
    viewed_at    TIMESTAMPTZ  DEFAULT NOW(),
    referrer     VARCHAR(500)
);

CREATE INDEX IF NOT EXISTS idx_pviews_portfolio ON portfolio_views (portfolio_id);
CREATE INDEX IF NOT EXISTS idx_pviews_date      ON portfolio_views (viewed_at);
