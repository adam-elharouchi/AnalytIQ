#!/bin/bash
# Script to set up reverse proxy on the server
# Run this on your production server where www.myanalytiq.org is hosted

set -e  # Exit on error

echo "🚀 Setting up Reverse Proxy for AnalytIQ"
echo "=========================================="
echo ""

# Colors for output
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
NC='\033[0m' # No Color

# Check if running as root
if [ "$EUID" -ne 0 ]; then 
    echo -e "${RED}❌ Please run as root (use sudo)${NC}"
    exit 1
fi

# Detect OS
if [ -f /etc/os-release ]; then
    . /etc/os-release
    OS=$ID
else
    echo -e "${RED}❌ Cannot detect OS${NC}"
    exit 1
fi

echo -e "${GREEN}✓ Detected OS: $OS${NC}"
echo ""

# Install Nginx
echo "📦 Installing Nginx..."
if [ "$OS" == "ubuntu" ] || [ "$OS" == "debian" ]; then
    apt update
    apt install -y nginx
elif [ "$OS" == "centos" ] || [ "$OS" == "rhel" ] || [ "$OS" == "fedora" ]; then
    yum install -y nginx
else
    echo -e "${YELLOW}⚠️  Please install Nginx manually for your OS${NC}"
    echo "   Then run this script again to configure it"
    exit 1
fi

echo -e "${GREEN}✓ Nginx installed${NC}"
echo ""

# Get project directory
PROJECT_DIR=$(pwd)
echo "📁 Project directory: $PROJECT_DIR"
echo ""
read -p "Is this correct? (y/n): " -n 1 -r
echo
if [[ ! $REPLY =~ ^[Yy]$ ]]; then
    read -p "Enter the full path to your AnalytIQ project: " PROJECT_DIR
fi

# Create Nginx configuration
echo ""
echo "📝 Creating Nginx configuration..."

if [ -d "/etc/nginx/sites-available" ]; then
    # Debian/Ubuntu style
    CONFIG_FILE="/etc/nginx/sites-available/myanalytiq"
    ENABLED_DIR="/etc/nginx/sites-enabled"
elif [ -d "/etc/nginx/conf.d" ]; then
    # CentOS/RHEL style
    CONFIG_FILE="/etc/nginx/conf.d/myanalytiq.conf"
    ENABLED_DIR=""
else
    CONFIG_FILE="/etc/nginx/myanalytiq.conf"
    ENABLED_DIR=""
fi

# Create config file
cat > "$CONFIG_FILE" <<EOF
# Nginx configuration for AnalytIQ
# Generated by setup_reverse_proxy.sh

server {
    listen 80;
    server_name www.myanalytiq.org myanalytiq.org;

    # Logging
    access_log /var/log/nginx/analytiq_access.log;
    error_log /var/log/nginx/analytiq_error.log;

    # Maximum upload size
    client_max_body_size 10M;

    # Serve static files (frontend)
    location / {
        root $PROJECT_DIR;
        index index.html;
        try_files \$uri \$uri/ /index.html;
        
        # Cache static assets
        location ~* \.(jpg|jpeg|png|gif|ico|css|js|svg|woff|woff2|ttf|eot)$ {
            expires 1y;
            add_header Cache-Control "public, immutable";
        }
    }

    # Proxy API requests to Flask backend
    location /api {
        proxy_pass http://127.0.0.1:5000;
        proxy_set_header Host \$host;
        proxy_set_header X-Real-IP \$remote_addr;
        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto \$scheme;
        
        # Timeouts
        proxy_connect_timeout 60s;
        proxy_send_timeout 60s;
        proxy_read_timeout 60s;
        
        # CORS headers (Flask also handles this)
        add_header 'Access-Control-Allow-Origin' '*' always;
        add_header 'Access-Control-Allow-Methods' 'GET, POST, PUT, DELETE, OPTIONS' always;
        add_header 'Access-Control-Allow-Headers' 'Content-Type, Authorization' always;
        
        if (\$request_method = 'OPTIONS') {
            add_header 'Access-Control-Allow-Origin' '*';
            add_header 'Access-Control-Allow-Methods' 'GET, POST, PUT, DELETE, OPTIONS';
            add_header 'Access-Control-Allow-Headers' 'Content-Type, Authorization';
            add_header 'Access-Control-Max-Age' 1728000;
            add_header 'Content-Type' 'text/plain; charset=utf-8';
            add_header 'Content-Length' 0;
            return 204;
        }
    }

    # Health check endpoint
    location /health {
        access_log off;
        return 200 "healthy\n";
        add_header Content-Type text/plain;
    }
}
EOF

echo -e "${GREEN}✓ Configuration file created: $CONFIG_FILE${NC}"

# Enable site (Debian/Ubuntu)
if [ -n "$ENABLED_DIR" ]; then
    if [ ! -f "$ENABLED_DIR/myanalytiq" ]; then
        ln -s "$CONFIG_FILE" "$ENABLED_DIR/myanalytiq"
        echo -e "${GREEN}✓ Site enabled${NC}"
    fi
fi

# Test Nginx configuration
echo ""
echo "🔍 Testing Nginx configuration..."
if nginx -t; then
    echo -e "${GREEN}✓ Nginx configuration is valid${NC}"
else
    echo -e "${RED}❌ Nginx configuration has errors${NC}"
    exit 1
fi

# Restart Nginx
echo ""
echo "🔄 Restarting Nginx..."
if systemctl restart nginx; then
    echo -e "${GREEN}✓ Nginx restarted successfully${NC}"
else
    service nginx restart
    echo -e "${GREEN}✓ Nginx restarted successfully${NC}"
fi

# Check Nginx status
if systemctl is-active --quiet nginx; then
    echo -e "${GREEN}✓ Nginx is running${NC}"
else
    echo -e "${YELLOW}⚠️  Nginx might not be running. Check status manually.${NC}"
fi

echo ""
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo -e "${GREEN}✅ Reverse Proxy Setup Complete!${NC}"
echo ""
echo "📍 Frontend: http://www.myanalytiq.org/"
echo "📍 API: http://www.myanalytiq.org/api"
echo ""
echo "⚠️  Next Steps:"
echo "   1. Make sure Flask backend is running on port 5000"
echo "   2. Set up Flask as a service (see SETUP_INSTRUCTIONS.md)"
echo "   3. Configure SSL/HTTPS (recommended)"
echo ""
echo "🧪 Test it:"
echo "   curl http://www.myanalytiq.org/api/health"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo ""

